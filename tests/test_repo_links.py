"""Every file path referenced in docs, reports, dashboards and code must exist in the repo.

Catches stale links (e.g. renamed docs) in README commands, markdown links and code comments.
Generated artefacts that only exist after `make all` are checked only when the pipeline has run.
"""
import re

import pytest

from conftest import PIPELINE_READY, ROOT

SCAN = [p for ext in ("*.md", "*.py", "*.dax", "*.m", "Makefile")
        for p in ROOT.rglob(ext) if ".venv" not in p.parts and ".pytest_cache" not in p.parts]
TOP_DIRS = ("docs", "reports", "sql", "python", "dashboard", "assets", "tests", "data", "outputs", "linkedin")
PATH_RE = re.compile(r"(?<![\w/.-])((?:%s)/[\w./-]*[\w-]\.(?:md|sql|py|csv|json|png|ipynb|dax|m|txt))" % "|".join(TOP_DIRS))
MD_LINK_RE = re.compile(r"\]\(((?!https?://|#|mailto:)[^)\s]+)\)")
GENERATED = ("data/bi/", "data/processed/", "data/raw/")


def _refs():
    for f in SCAN:
        text = f.read_text(errors="ignore")
        for m in PATH_RE.finditer(text):
            yield f, m.group(1), ROOT / m.group(1)
        if f.suffix == ".md":
            for m in MD_LINK_RE.finditer(text):
                yield f, m.group(1), (f.parent / m.group(1).split("#")[0]).resolve()


@pytest.mark.parametrize("src,ref,target", list(_refs()), ids=lambda x: str(x)[-60:] if not isinstance(x, str) else x)
def test_reference_exists(src, ref, target):
    if ref.startswith(GENERATED) and not PIPELINE_READY:
        pytest.skip("generated by the pipeline")
    if "*" in ref or "<" in ref:
        pytest.skip("pattern, not a path")
    assert target.exists(), f"{src.relative_to(ROOT)} references missing path: {ref}"
